"""Refresh the published design kit from the checked-in sources, or check for drift."""

import argparse
from html import escape
import json
from pathlib import Path
import sys
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "wsurf.app/design-system"
CATALOG = ROOT / "WSurf/Assets.xcassets"
BRAND = ROOT / "branding/tandem"
START = "<!-- Asset catalogue starts here. Generated by Tools/update-design-system.py. -->"
END = "<!-- Asset catalogue ends here. -->"


def source_art():
    """The app and branding sources own renditions that are also published on the web."""
    files = {"assets/Dock/metal.png": CATALOG / "AppIcon.appiconset/icon_512x512.png"}
    for name in ("Steel", "Copper"):
        files[f"assets/Dock/{name.lower()}.png"] = (
            CATALOG / f"AlternateIcons/AlternateIcon{name}.appiconset/icon_512x512.png"
        )
    for name in ("Light", "Dark", "Mono"):
        asset = f"AlternateIcon{name}"
        files[f"assets/Dock/{name.lower()}.png"] = CATALOG / f"AlternateIcons/{asset}.imageset/{asset}.png"
    for section, pattern in (
        ("Mark", "mark/*.svg"), ("Lockup", "lockup/lockup*.svg"),
        ("Lockup", "wordmark/*.svg"), ("Mono", "mono/*.svg"),
        ("Icons", "favicon/*"), ("Icons", "icon/*.svg"), ("Icons", "icon/*-1024.png"),
        ("Icons", "icon/Tandem.icon/Assets/*.svg"), ("Motion", "loader/web/*.css"),
        ("Motion", "loader/app/*.swift"), ("Motion", "loader/video/*.mp4"),
        ("Motion", "loader/video/*.gif"),
    ):
        for source in sorted(BRAND.glob(pattern)):
            section_name = "Mono" if source.stem in {"lockup-black", "lockup-white", "lockup-mono"} else section
            files[f"assets/{section_name}/{source.name}"] = source
    files["assets/Icons/icon.json"] = BRAND / "icon/Tandem.icon/icon.json"
    files["assets/Lockup/Inter-OFL.txt"] = ROOT / "branding/licenses/Inter-OFL.txt"
    files["assets/Flux/Figtree-OFL.txt"] = ROOT / "branding/licenses/Figtree-OFL.txt"
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report outdated files without writing")
    check = parser.parse_args().check
    changed = []

    def publish(name, data):
        path = KIT / name
        if path.is_file() and path.read_bytes() == data:
            return
        changed.append(name)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

    for name, source in source_art().items():
        publish(name, source.read_bytes())

    groups = {}
    markup = []
    for group in sorted((KIT / "assets").iterdir(), key=lambda path: path.name.casefold()):
        if not group.is_dir():
            continue
        guide = group / "README.md"
        if not guide.is_file():
            raise ValueError(f"Missing usage guide: {guide}")
        paths = sorted(path for path in group.iterdir() if path.is_file() and not path.name.startswith("."))
        names = [path.relative_to(KIT).as_posix() for path in paths if path != guide]
        guide_url = guide.relative_to(KIT).as_posix()
        groups[group.name] = {"guide": guide_url, "files": names}
        markup.extend([
            '          <details class="asset-group">',
            f'            <summary>{escape(group.name)} <span>{len(names)} files</span></summary>',
            f'            <a href="{quote(guide_url)}">{escape(group.name)} usage guide</a>',
            '            <ul class="file-list">',
        ])
        for name in names:
            markup.append(f'              <li><a href="{quote(name)}">{escape(Path(name).name)}</a></li>')
        markup.extend(["            </ul>", "          </details>"])

    components = {}
    for preview in sorted((KIT / "components").glob("*/preview.html")):
        entry = {"preview": preview.relative_to(KIT).as_posix()}
        guide = preview.with_name("README.md")
        if guide.is_file():
            entry["guide"] = guide.relative_to(KIT).as_posix()
        components[preview.parent.name] = entry
    walkthroughs = {}
    for name in ("spaces", "micro"):
        files = {"film": f"../media/demos/{name}.mp4", "poster": f"../media/demos/{name}.jpg"}
        for path in files.values():
            if not (KIT / path).is_file():
                raise FileNotFoundError(path)
        walkthroughs[name] = files
    manifest = {
        "name": "WSurf Design System",
        "guide": "README.md",
        "instructions": "AI.md",
        "tokens": {"data": "tokens.json", "css": "tokens.css"},
        "componentStyles": "components/bundle.css",
        "components": components,
        "assets": groups,
        "walkthroughs": walkthroughs,
    }
    publish("manifest.json", (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode())

    page = (KIT / "index.html").read_text()
    before, contents = page.split(START)
    _, after = contents.split(END)
    publish("index.html", (before + START + "\n" + "\n".join(markup) + "\n          " + END + after).encode())
    if check and changed:
        print("Out of date: " + ", ".join(changed), file=sys.stderr)
        return 1
    print(f"Design kit: {len(groups)} asset groups, {len(components)} component previews, {len(changed)} updated files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
