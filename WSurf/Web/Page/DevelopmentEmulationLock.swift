import Foundation

/// Runs a page's development emulation changes strictly one at a time, first come first served, so an older lease's cleanup
/// can never land after a newer lease applied its own.
@MainActor
final class DevelopmentEmulationLock {
    private var busy = false
    private var waiters: [CheckedContinuation<Void, Never>] = []

    func acquire() async {
        guard busy else {
            busy = true
            return
        }
        await withCheckedContinuation { waiters.append($0) }
    }

    func release() {
        if waiters.isEmpty { busy = false } else { waiters.removeFirst().resume() }
    }
}
